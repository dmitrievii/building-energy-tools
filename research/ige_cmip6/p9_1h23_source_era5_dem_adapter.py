#!/usr/bin/env python3
"""P9.1H2/H3 adapter to already implemented P9.1F SRTM ring + P9.1E ARCO grid.

No provider queries here. Original source provenance is mandatory. Reuses
P9.1F fields, not 2019 observational residuals, and accepts only frozen 2022 AT/DE/CH windows.
"""
from __future__ import annotations
import datetime as dt
import math
from p9_1h23_physical_inversion_candidate import State,baselines,evaluate,clamp
from p9_1h_regional_AT_DE_CH_guard import qualification_scope

FROZEN_P9F_12KM_P75_RELIEF_GATE_M=120.
FROZEN_P9F_GRID_DELTA_GATE_M=-150.
FROZEN_P9F_RING_UPHILL_OFFSET_M=50.

def index_from_existing_P9F1_original_srtm(terrain:dict, site_height_m:float,
                                             regular_arco_grid_height_m:float)->dict:
    """Independent DEM shape only; never source station observed 2m temperature.

    Geometry is the original SRTM 12km 8-ray ring generated by
    p9_1f1_terrain_inversion_2019_holdout.independent_dem_rings.
    """
    if terrain.get("source_station_QC_temperature_was_never_used_to_derive_terrain") is not True:
        raise ValueError("P9H23_SRTM_NOT_INDEPENDENT_OF_STATION_TARGET")
    if terrain.get("terrain_inferred_valley_susceptibility_only_not_inversion_detection") is not True:
        raise ValueError("P9H23_TERRAIN_SOURCE_SEMANTICS_NOT_VERIFIED")
    ring=terrain.get("ring12km_m")
    if not isinstance(ring,list) or len(ring)!=8:
        raise ValueError("P9H23_NOT_REGISTERED_P9F1_EIGHT_RAY_RING")
    center=float(terrain["original_srtm90m_site_m"])
    site_z=float(site_height_m);grid_z=float(regular_arco_grid_height_m)
    heights=[float(x) for x in ring]
    if not all(math.isfinite(x) and -500<x<9000 for x in [center,site_z,grid_z,*heights]):
        raise ValueError("P9H23_NONFINITE_SRTM_OR_MODEL_HEIGHT")
    if abs(center-site_z)>200:
        raise ValueError("P9H23_OFFICIAL_SITE_SRTM_MISMATCH_TOO_LARGE")
    # Recalculate P9F1 original 12-km p75 rather than trusting any external summary.
    sorted_h=sorted(heights)
    q=.75*(len(sorted_h)-1)
    lo=int(math.floor(q));up=int(math.ceil(q))
    p75=sorted_h[lo]*(up-q)+sorted_h[up]*(q-lo)
    relief=p75-center
    source_relief=float(terrain["ring12km_p75_relief_m"])
    if abs(relief-source_relief)>1e-5:
        raise ValueError("P9H23_P9F1_ORIGINAL_TERRAIN_P75_INCONSISTENT")
    fraction=sum(z>center+FROZEN_P9F_RING_UPHILL_OFFSET_M for z in heights)/8
    if abs(fraction-float(terrain["ring12km_uphill_fraction"]))>1e-6:
        raise ValueError("P9H23_P9F1_UPHILL_FRACTION_INCONSISTENT")
    dz=site_z-grid_z
    eligible=(relief>=FROZEN_P9F_12KM_P75_RELIEF_GATE_M
              and dz<=FROZEN_P9F_GRID_DELTA_GATE_M)
    # Purely hypothesis-level ramps; 240m and 350m fixed prior to scoring,
    # neither observed 2018 Hyytiälä nor frozen 2022 AT/DE/CH temperature outcomes selected these numbers.
    index=(clamp((relief-FROZEN_P9F_12KM_P75_RELIEF_GATE_M)/240.)
           *clamp((-dz-150.)/350.)*fraction) if eligible else 0.
    return {"terrain_cold_pool_index":index,
            "original_P9F1_12km_p75_relief_m":relief,
            "ERA5_regular_grid_minus_site_height_m":-dz,
            "P9F1_srtm_12km_ring_uphill_fraction":fraction,
            "frozen_prior_geometric_gates_passed":eligible,
            "source_original_SRTM_ring_not_requeried":True,
            "terrain_index_not_validation_of_actual_inversion":True}


def predict_one_frozen_regional_hour(*,country_code:str,timestamp_utc:str,latitude:float,longitude:float,
                                        source_weather_era5:dict,site_height_m:float,
                                        source_arco_grid_cell:dict,source_original_srtm:dict,
                                        provider_altitude_2m_c:float|None=None)->dict:
    """Caller passes source-verified original ERA5 and original SRTM/ARCO.

    Regional cohort only: three countries, two registered 2022 seven-day windows.
    No implicit source retrieval or retroactive reuse of 2019 target-station errors.
    """
    country_code,normalized_stamp=qualification_scope(country_code,timestamp_utc)
    stamp=dt.datetime.fromisoformat(normalized_stamp)
    if not -90<=latitude<=90 or not -180<=longitude<=180:
        raise ValueError("P9H23_SITE_GEOGRAPHY_INVALID")
    if source_arco_grid_cell.get("same_ERA5_grid_node_coordinate_as_OpenMeteo") is not True:
        raise ValueError("P9H23_ARCO_ERA5_OROGRAPHY_NOT_MATCHED")
    if source_arco_grid_cell.get("same_model_topographic_interpolation_proven") is True:
        # This provenance claim is unsupported by P9.1E; fail to prevent
        # accidentally introducing unsubstantiated equivalence.
        raise ValueError("P9H23_IMPOSSIBLE_PROVIDER_REGRID_CERTIFICATION")
    gridz=float(source_arco_grid_cell["ARCO_025_original_model_height_m"])
    morph=index_from_existing_P9F1_original_srtm(
        source_original_srtm,site_height_m,gridz)
    weather=source_weather_era5
    initial=baselines(float(weather["temperature_2m"]),gridz,site_height_m,
                      provider_altitude_2m_c)
    state=State(timestamp_utc=stamp,latitude_deg=latitude,longitude_deg=longitude,
                cloud_cover_percent=weather.get("cloud_cover"),
                wind_speed_10m_ms=weather.get("wind_speed_10m"),
                terrain_cold_pool_index=morph["terrain_cold_pool_index"],
                independently_verified_snow_cover=None)
    result=evaluate(state,initial["B1_native_grid_fixed_lapse_C"])
    return {"phase":"P9H23_AT_DE_CH_FROZEN_2022_EVALUATION",
            "country_code":country_code,
            "physically_bounded_temperature_C":result.corrected_temperature_c,
            "physical_correction_C":result.correction_c,
            "physical_status":result.status,
            "computed_inversion_risk_proxy":result.inversion_risk_proxy,
            "three_baselines":initial,
            "original_dem_morphology":morph,
            "source_wind_and_cloud_only_no_measured_flux_closure":True,
            "real_observed_2m_station_MAE_unavailable":True,
            "source_snow_not_yet_qualified":True,
            "independent_2021_Nordic_holdout_unread":True,
            "regional_AT_DE_CH_qualified":False,
            "global_arbitrary_point_weather_qualified":False,
            "production_epw_ready":False}
